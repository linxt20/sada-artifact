#!/usr/bin/env python3
"""Render every LLM-facing prompt of Experiments 1-5 into per-experiment files.

The prompt files under `3_experiments/*/prompts/` are generated, not hand-copied:
each is rendered by importing the module that owns the prompt and either reading
its module-level constant or calling its `build_prompt` with placeholder
arguments. Re-run this script to confirm the files still match the code.

    python3 3_experiments/_extract_prompts.py            # write the files
    python3 3_experiments/_extract_prompts.py --check    # verify, write nothing

Only the standard library is required. No model is called.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path
from typing import Any, Callable

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CODE = ROOT / "4_code"

EXP = {
    1: HERE / "exp1_end_to_end_utility",
    2: HERE / "exp2_analysis_form",
    3: HERE / "exp3_schema_suitability",
    4: HERE / "exp4_scale_and_grounding",
    5: HERE / "exp5_predictive_features",
}

# Placeholders substituted into the builders. They are obviously fake so that a
# reader cannot mistake a rendered prompt for a real judged instance.
Q = "{analytical query}"
COLS = ["{original_column_1}", "{original_column_2}"]
ADDED = [{"name": "{added_column}", "dtype": "categorical", "values": ["{value_a}", "{value_b}"]}]


def load(relative: str) -> Any:
    path = CODE / relative
    directory = str(path.parent)
    if directory not in sys.path:
        sys.path.insert(0, directory)
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    # Registered before execution because some of these modules use @dataclass,
    # which resolves annotations through sys.modules at class-creation time.
    sys.modules[path.stem] = module
    spec.loader.exec_module(module)
    return module


def header(title: str, source: str, note: str = "") -> str:
    lines = [
        f"# {title}",
        "",
        f"Source of truth: `4_code/{source}`",
        "",
        "Generated by `3_experiments/_extract_prompts.py`. Do not edit by hand;",
        "edit the source and re-run the extractor.",
    ]
    if note:
        lines += ["", note]
    lines += ["", "---", "", "```text"]
    return "\n".join(lines)


def emit(target: Path, title: str, source: str, body: str, note: str = "") -> tuple[Path, str]:
    return target, header(title, source, note) + "\n" + body.rstrip("\n") + "\n```\n"


def build() -> list[tuple[Path, str]]:
    out: list[tuple[Path, str]] = []

    # ---- Experiment 1: analyst prompts + the pairwise judge -------------------
    reports = load("benchmark/gen_augment_table_reports.py")
    out.append(emit(
        EXP[1] / "prompts" / "analyst_prompt_all_conditions.md",
        "Analyst prompt (original, skill_off, skill_on)",
        "benchmark/gen_augment_table_reports.py (PROMPT_TEMPLATE)",
        reports.PROMPT_TEMPLATE,
        "One prompt is shared by all three conditions, so the analyst is never told\n"
        "which columns are augmented. Experiment 2 classifies the reports this\n"
        "prompt produced, so it applies there too.",
    ))
    out.append(emit(
        EXP[1] / "prompts" / "analyst_prompt_skill_on_e2e.md",
        "Analyst prompt (skill_on_e2e only)",
        "benchmark/gen_augment_table_reports.py (E2E_PROMPT_TEMPLATE)",
        reports.E2E_PROMPT_TEMPLATE,
        "The one condition that is told an augmentation already happened, and is\n"
        "pointed at the operator workdir.",
    ))
    grader = load("benchmark/score_semantic_recall/grader_v3.py")
    out.append(emit(
        EXP[1] / "prompts" / "judge_pairwise_report_grading.md",
        "Judge prompt: pairwise report grading (appendix D.1)",
        "benchmark/score_semantic_recall/grader_v3.py (PAIRWISE_PROMPT)",
        grader.PAIRWISE_PROMPT,
    ))

    # ---- Experiment 2 --------------------------------------------------------
    form = load("benchmark/classify_form_update.py")
    out.append(emit(
        EXP[2] / "prompts" / "judge_analytical_form_classification.md",
        "Judge prompt: analytical-form classification (appendix D.2)",
        "benchmark/classify_form_update.py (PROMPT)",
        form.PROMPT,
    ))

    # ---- Experiment 3: one rendered prompt per intent sub-type ---------------
    b2 = load("benchmark/scorer_v2/b2_characteristic_adherence.py")
    for subtype in sorted(b2._RUBRICS):
        out.append(emit(
            EXP[3] / "prompts" / f"judge_adherence_{subtype}.md",
            f"Judge prompt: characteristic adherence, {subtype} (appendix D.3)",
            "benchmark/scorer_v2/b2_characteristic_adherence.py (build_prompt)",
            b2.build_prompt(
                subtype=subtype, query=Q, focus="{focus_variable}",
                concept="{concept_to_decompose}", source_columns=COLS, columns_payload=ADDED,
            ),
            "The shared frame is identical across sub-types; only the spliced-in\n"
            "rubric differs. All six rendered variants are in this directory.",
        ))
    b1 = load("benchmark/scorer_v2/b1_general_quality.py")
    out.append(emit(
        EXP[3] / "prompts" / "judge_general_quality.md",
        "Judge prompt: general augmentation quality",
        "benchmark/scorer_v2/b1_general_quality.py (build_prompt)",
        b1.build_prompt(query=Q, source_columns=COLS, columns_payload=ADDED,
                        row_evidence=[{"row_index": 0, "source_row": {"{column}": "{text}"}}]),
        "Reported as a component signal, not as a headline table.",
    ))

    # ---- Experiment 4 -------------------------------------------------------
    augmenter = load("benchmark/augmenter/run_skill_off_agentic_augment.py")
    out.append(emit(
        EXP[4] / "prompts" / "baseline_agentic_augmentation.md",
        "Baseline (skill_off) agentic augmentation prompt",
        "benchmark/augmenter/run_skill_off_agentic_augment.py (_agent_prompt)",
        augmenter._agent_prompt(Q, csv_hygiene=True),
        "This is the whole instruction the skill_off condition receives. It\n"
        "constrains only the deliverable's CSV format, never what the columns\n"
        "should be, so it leaks none of the operator's analytical guidance.",
    ))
    judge = load("benchmark/scorer_grounding/_g_judge.py")
    out.append(emit(
        EXP[4] / "prompts" / "judge_row_level_grounding.md",
        "Judge prompt: row-level grounding audit (appendix D.4)",
        "benchmark/scorer_grounding/_g_judge.py (SYSTEM)",
        judge.SYSTEM,
        "Sent with a batch of rows appended under a `== BATCH ==` marker; see\n"
        "`build_prompt` in the same file.",
    ))

    # ---- Experiment 5 -------------------------------------------------------
    skilloff = load("TextTabBench/augment_process_result_v11_update/skilloff_augment.py")
    out.append(emit(
        EXP[5] / "prompts" / "baseline_augmentation.md",
        "Baseline (skill_off) augmentation prompt",
        "TextTabBench/augment_process_result_v11_update/skilloff_augment.py (PROMPT)",
        skilloff.PROMPT,
    ))

    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify without writing")
    args = parser.parse_args()

    stale, written = [], 0
    for target, content in build():
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(target.relative_to(ROOT))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
            written += 1

    if args.check:
        if stale:
            print("Stale or missing prompt files:")
            for path in stale:
                print(f"  {path}")
            return 1
        print("All prompt files match the code.")
        return 0
    print(f"Wrote {written} prompt files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
